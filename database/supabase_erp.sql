-- SmartPlanet ERP schema (Postgres / Supabase)
CREATE TABLE IF NOT EXISTS schema_migrations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  migration VARCHAR(191) NOT NULL UNIQUE,
  batch INTEGER NOT NULL,
  applied_at TIMESTAMP NOT NULL
);

CREATE TABLE companies (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  legal_name VARCHAR(191) NOT NULL,
  trade_name VARCHAR(191) NOT NULL,
  document VARCHAR(20),
  email VARCHAR(191),
  phone VARCHAR(30),
  timezone VARCHAR(64) NOT NULL DEFAULT 'America/Sao_Paulo',
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  UNIQUE (document)
);

CREATE TABLE branches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  name VARCHAR(191) NOT NULL,
  code VARCHAR(40) NOT NULL,
  document VARCHAR(20),
  address_json TEXT,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  UNIQUE (company_id, code)
);

CREATE TABLE roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  name VARCHAR(100) NOT NULL,
  description VARCHAR(255),
  created_at TIMESTAMP NOT NULL,
  UNIQUE (company_id, name)
);

CREATE TABLE permissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(100) NOT NULL UNIQUE,
  description VARCHAR(255) NOT NULL
);

CREATE TABLE role_permissions (
  role_id BIGINT NOT NULL REFERENCES roles(id) ON DELETE CASCADE,
  permission_id BIGINT NOT NULL REFERENCES permissions(id) ON DELETE CASCADE,
  PRIMARY KEY (role_id, permission_id)
);

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  role_id BIGINT NOT NULL REFERENCES roles(id),
  name VARCHAR(191) NOT NULL,
  email VARCHAR(191) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  is_master INTEGER NOT NULL DEFAULT 0,
  last_login_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  UNIQUE (company_id, email)
);

CREATE TABLE password_reset_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash VARCHAR(255) NOT NULL UNIQUE,
  expires_at TIMESTAMP NOT NULL,
  used_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL
);

CREATE TABLE login_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(191) NOT NULL,
  ip_address VARCHAR(64) NOT NULL,
  succeeded INTEGER NOT NULL,
  attempted_at TIMESTAMP NOT NULL
);

CREATE TABLE audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT REFERENCES companies(id),
  branch_id BIGINT REFERENCES branches(id),
  user_id BIGINT REFERENCES users(id),
  action VARCHAR(100) NOT NULL,
  entity_type VARCHAR(100) NOT NULL,
  entity_id VARCHAR(100),
  before_json TEXT,
  after_json TEXT,
  ip_address VARCHAR(64),
  user_agent VARCHAR(500),
  created_at TIMESTAMP NOT NULL
);

CREATE TABLE settings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT REFERENCES branches(id),
  user_id BIGINT REFERENCES users(id),
  setting_key VARCHAR(191) NOT NULL,
  setting_value TEXT,
  updated_at TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX ux_settings_key ON settings (company_id, COALESCE(branch_id, 0), COALESCE(user_id, 0), setting_key);

CREATE TABLE categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  parent_id BIGINT REFERENCES categories(id),
  name VARCHAR(191) NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX ux_categories_name ON categories (company_id, COALESCE(parent_id, 0), name);

CREATE TABLE brands (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  name VARCHAR(191) NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  UNIQUE (company_id, name)
);

CREATE TABLE units (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  code VARCHAR(12) NOT NULL,
  name VARCHAR(80) NOT NULL,
  decimal_places INTEGER NOT NULL DEFAULT 0,
  active INTEGER NOT NULL DEFAULT 1,
  UNIQUE (company_id, code)
);

CREATE TABLE suppliers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  name VARCHAR(191) NOT NULL,
  document VARCHAR(20),
  email VARCHAR(191),
  phone VARCHAR(30),
  address_json TEXT,
  notes TEXT,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX ux_suppliers_document ON suppliers (company_id, document) WHERE document IS NOT NULL;

CREATE TABLE customers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  name VARCHAR(191) NOT NULL,
  document VARCHAR(20),
  email VARCHAR(191),
  phone VARCHAR(30),
  birth_date DATE,
  address_json TEXT,
  notes TEXT,
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX ux_customers_document ON customers (company_id, document) WHERE document IS NOT NULL;

CREATE TABLE products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  category_id BIGINT REFERENCES categories(id),
  brand_id BIGINT REFERENCES brands(id),
  unit_id BIGINT NOT NULL REFERENCES units(id),
  main_supplier_id BIGINT REFERENCES suppliers(id),
  internal_code VARCHAR(64) NOT NULL,
  type VARCHAR(20) NOT NULL DEFAULT 'product',
  description VARCHAR(400) NOT NULL,
  complementary_name VARCHAR(191),
  model VARCHAR(100),
  cost_price DECIMAL(15,2) NOT NULL DEFAULT 0,
  sale_price DECIMAL(15,2) NOT NULL DEFAULT 0,
  promotional_price DECIMAL(15,2),
  promotion_starts_at TIMESTAMP,
  promotion_ends_at TIMESTAMP,
  minimum_stock DECIMAL(15,4) NOT NULL DEFAULT 0,
  track_stock INTEGER NOT NULL DEFAULT 1,
  active INTEGER NOT NULL DEFAULT 1,
  notes TEXT,
  image_path VARCHAR(255),
  ncm VARCHAR(10),
  cest VARCHAR(10),
  origin_code VARCHAR(4),
  cfop VARCHAR(8),
  cst_csosn VARCHAR(8),
  version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  UNIQUE (company_id, internal_code),
  CHECK (type IN ('product','service')),
  CHECK (cost_price >= 0 AND sale_price >= 0)
);

CREATE TABLE product_barcodes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  barcode VARCHAR(64) NOT NULL,
  symbology VARCHAR(20) NOT NULL DEFAULT 'CODE128',
  is_primary INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL,
  UNIQUE (company_id, barcode)
);

CREATE TABLE product_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES products(id),
  user_id BIGINT REFERENCES users(id),
  snapshot_json TEXT NOT NULL,
  reason VARCHAR(255),
  created_at TIMESTAMP NOT NULL
);

CREATE TABLE stock_locations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  code VARCHAR(40) NOT NULL,
  name VARCHAR(191) NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  UNIQUE (company_id, code)
);

CREATE TABLE stock_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  location_id BIGINT NOT NULL REFERENCES stock_locations(id),
  product_id BIGINT NOT NULL REFERENCES products(id),
  movement_type VARCHAR(30) NOT NULL,
  quantity DECIMAL(15,4) NOT NULL,
  unit_cost DECIMAL(15,2),
  source_type VARCHAR(40) NOT NULL,
  source_id VARCHAR(100) NOT NULL,
  source_line VARCHAR(100) NOT NULL DEFAULT '',
  reason VARCHAR(255),
  user_id BIGINT REFERENCES users(id),
  occurred_at TIMESTAMP NOT NULL,
  UNIQUE (company_id, source_type, source_id, source_line),
  CHECK (quantity <> 0)
);

CREATE TABLE inventory_counts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  location_id BIGINT NOT NULL REFERENCES stock_locations(id),
  status VARCHAR(20) NOT NULL DEFAULT 'open',
  notes TEXT,
  started_by BIGINT NOT NULL REFERENCES users(id),
  started_at TIMESTAMP NOT NULL,
  closed_by BIGINT REFERENCES users(id),
  closed_at TIMESTAMP
);

CREATE TABLE inventory_count_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  inventory_count_id BIGINT NOT NULL REFERENCES inventory_counts(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id),
  expected_quantity DECIMAL(15,4) NOT NULL,
  counted_quantity DECIMAL(15,4),
  UNIQUE (inventory_count_id, product_id)
);

CREATE TABLE cash_registers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  name VARCHAR(100) NOT NULL,
  code VARCHAR(40) NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  UNIQUE (company_id, code)
);

CREATE TABLE cash_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  cash_register_id BIGINT NOT NULL REFERENCES cash_registers(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  status VARCHAR(20) NOT NULL DEFAULT 'open',
  opening_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  opened_at TIMESTAMP NOT NULL,
  opening_notes TEXT,
  expected_cash DECIMAL(15,2),
  counted_cash DECIMAL(15,2),
  difference_amount DECIMAL(15,2),
  closing_notes TEXT,
  closing_reason VARCHAR(255),
  open_guard VARCHAR(40),
  closed_by BIGINT REFERENCES users(id),
  closed_at TIMESTAMP
);
CREATE UNIQUE INDEX ux_cash_session_open ON cash_sessions (company_id, branch_id, cash_register_id, open_guard);

CREATE TABLE cash_movements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cash_session_id BIGINT NOT NULL REFERENCES cash_sessions(id),
  movement_type VARCHAR(30) NOT NULL,
  amount DECIMAL(15,2) NOT NULL,
  reason VARCHAR(255) NOT NULL,
  source_type VARCHAR(40),
  source_id VARCHAR(100),
  user_id BIGINT NOT NULL REFERENCES users(id),
  authorized_by BIGINT REFERENCES users(id),
  created_at TIMESTAMP NOT NULL,
  CHECK (amount > 0)
);
CREATE UNIQUE INDEX ux_cash_movement_source ON cash_movements (cash_session_id, movement_type, COALESCE(source_type, ''), COALESCE(source_id, ''));

CREATE TABLE payment_methods (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  code VARCHAR(40) NOT NULL,
  name VARCHAR(100) NOT NULL,
  method_type VARCHAR(30) NOT NULL,
  requires_confirmation INTEGER NOT NULL DEFAULT 1,
  max_installments INTEGER NOT NULL DEFAULT 1,
  active INTEGER NOT NULL DEFAULT 1,
  UNIQUE (company_id, code)
);

CREATE TABLE sales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  cash_session_id BIGINT REFERENCES cash_sessions(id),
  customer_id BIGINT REFERENCES customers(id),
  operator_id BIGINT NOT NULL REFERENCES users(id),
  sale_number VARCHAR(40) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft',
  subtotal DECIMAL(15,2) NOT NULL DEFAULT 0,
  discount_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  total DECIMAL(15,2) NOT NULL DEFAULT 0,
  idempotency_key VARCHAR(100) NOT NULL,
  notes TEXT,
  completed_at TIMESTAMP,
  cancelled_at TIMESTAMP,
  cancelled_by BIGINT REFERENCES users(id),
  cancellation_reason VARCHAR(255),
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  UNIQUE (company_id, sale_number),
  UNIQUE (company_id, idempotency_key)
);

CREATE TABLE sale_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id BIGINT NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id),
  barcode VARCHAR(64),
  description VARCHAR(400) NOT NULL,
  quantity DECIMAL(15,4) NOT NULL,
  unit_price DECIMAL(15,2) NOT NULL,
  discount_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  subtotal DECIMAL(15,2) NOT NULL,
  returned_quantity DECIMAL(15,4) NOT NULL DEFAULT 0,
  CHECK (quantity > 0)
);

CREATE TABLE sale_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_id BIGINT NOT NULL REFERENCES sales(id) ON DELETE CASCADE,
  payment_method_id BIGINT NOT NULL REFERENCES payment_methods(id),
  amount DECIMAL(15,2) NOT NULL,
  installments INTEGER NOT NULL DEFAULT 1,
  status VARCHAR(20) NOT NULL DEFAULT 'confirmed',
  operational_confirmation INTEGER NOT NULL DEFAULT 0,
  reference VARCHAR(100),
  created_at TIMESTAMP NOT NULL,
  CHECK (amount > 0)
);
CREATE UNIQUE INDEX ux_sale_payment_once ON sale_payments (sale_id, payment_method_id, COALESCE(reference, ''));

CREATE TABLE purchase_orders (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  supplier_id BIGINT NOT NULL REFERENCES suppliers(id),
  order_number VARCHAR(40) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft',
  expected_at TIMESTAMP,
  subtotal DECIMAL(15,2) NOT NULL DEFAULT 0,
  discount_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  freight_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  total DECIMAL(15,2) NOT NULL DEFAULT 0,
  notes TEXT,
  created_by BIGINT NOT NULL REFERENCES users(id),
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  UNIQUE (company_id, order_number)
);

CREATE TABLE purchase_order_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id BIGINT NOT NULL REFERENCES purchase_orders(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id),
  quantity DECIMAL(15,4) NOT NULL,
  received_quantity DECIMAL(15,4) NOT NULL DEFAULT 0,
  unit_cost DECIMAL(15,2) NOT NULL,
  discount_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  subtotal DECIMAL(15,2) NOT NULL,
  CHECK (quantity > 0)
);

CREATE TABLE purchase_receipts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id BIGINT NOT NULL REFERENCES purchase_orders(id),
  receipt_number VARCHAR(40) NOT NULL,
  location_id BIGINT NOT NULL REFERENCES stock_locations(id),
  received_by BIGINT NOT NULL REFERENCES users(id),
  received_at TIMESTAMP NOT NULL,
  notes TEXT,
  idempotency_key VARCHAR(100),
  UNIQUE (purchase_order_id, receipt_number)
);
CREATE UNIQUE INDEX ux_purchase_receipt_idempotency ON purchase_receipts (purchase_order_id, idempotency_key);

CREATE TABLE purchase_receipt_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_receipt_id BIGINT NOT NULL REFERENCES purchase_receipts(id) ON DELETE CASCADE,
  purchase_order_item_id BIGINT NOT NULL REFERENCES purchase_order_items(id),
  quantity DECIMAL(15,4) NOT NULL,
  unit_cost DECIMAL(15,2) NOT NULL,
  created_at TIMESTAMP NOT NULL,
  UNIQUE (purchase_receipt_id, purchase_order_item_id),
  CHECK (quantity > 0)
);

CREATE TABLE quotes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  customer_id BIGINT REFERENCES customers(id),
  quote_number VARCHAR(40) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'draft',
  subtotal DECIMAL(15,2) NOT NULL DEFAULT 0,
  discount_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  total DECIMAL(15,2) NOT NULL DEFAULT 0,
  valid_until DATE,
  converted_sale_id BIGINT REFERENCES sales(id),
  created_by BIGINT NOT NULL REFERENCES users(id),
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  idempotency_key VARCHAR(100),
  UNIQUE (company_id, quote_number)
);
CREATE UNIQUE INDEX ux_quote_idempotency ON quotes (company_id, idempotency_key);

CREATE TABLE quote_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_id BIGINT NOT NULL REFERENCES quotes(id) ON DELETE CASCADE,
  product_id BIGINT NOT NULL REFERENCES products(id),
  description VARCHAR(400) NOT NULL,
  quantity DECIMAL(15,4) NOT NULL,
  unit_price DECIMAL(15,2) NOT NULL,
  discount_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  subtotal DECIMAL(15,2) NOT NULL
);

CREATE TABLE sale_returns (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  sale_id BIGINT NOT NULL REFERENCES sales(id),
  return_number VARCHAR(40) NOT NULL,
  return_type VARCHAR(20) NOT NULL DEFAULT 'refund',
  total DECIMAL(15,2) NOT NULL,
  reason VARCHAR(255) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'confirmed',
  created_by BIGINT NOT NULL REFERENCES users(id),
  authorized_by BIGINT REFERENCES users(id),
  created_at TIMESTAMP NOT NULL,
  idempotency_key VARCHAR(100),
  UNIQUE (company_id, return_number)
);
CREATE UNIQUE INDEX ux_return_idempotency ON sale_returns (company_id, idempotency_key);

CREATE TABLE sale_return_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sale_return_id BIGINT NOT NULL REFERENCES sale_returns(id) ON DELETE CASCADE,
  sale_item_id BIGINT NOT NULL REFERENCES sale_items(id),
  quantity DECIMAL(15,4) NOT NULL,
  amount DECIMAL(15,2) NOT NULL,
  return_to_stock INTEGER NOT NULL DEFAULT 1,
  CHECK (quantity > 0)
);

CREATE TABLE financial_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT REFERENCES branches(id),
  name VARCHAR(191) NOT NULL,
  account_type VARCHAR(30) NOT NULL,
  bank_code VARCHAR(10),
  agency VARCHAR(30),
  account_number VARCHAR(40),
  active INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE financial_categories (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  parent_id BIGINT REFERENCES financial_categories(id),
  name VARCHAR(191) NOT NULL,
  direction VARCHAR(10) NOT NULL,
  active INTEGER NOT NULL DEFAULT 1,
  code VARCHAR(40)
);
CREATE UNIQUE INDEX ux_financial_category_code ON financial_categories (company_id, code);
CREATE UNIQUE INDEX ux_financial_category_name ON financial_categories (company_id, COALESCE(parent_id, 0), name, direction);

CREATE TABLE financial_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  category_id BIGINT REFERENCES financial_categories(id),
  customer_id BIGINT REFERENCES customers(id),
  supplier_id BIGINT REFERENCES suppliers(id),
  direction VARCHAR(10) NOT NULL,
  description VARCHAR(255) NOT NULL,
  document_number VARCHAR(80),
  issue_date DATE NOT NULL,
  due_date DATE NOT NULL,
  amount DECIMAL(15,2) NOT NULL,
  settled_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'open',
  source_type VARCHAR(40),
  source_id VARCHAR(100),
  installment_number INTEGER NOT NULL DEFAULT 1,
  installment_count INTEGER NOT NULL DEFAULT 1,
  created_by BIGINT NOT NULL REFERENCES users(id),
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL
);
CREATE UNIQUE INDEX ux_financial_source ON financial_entries (company_id, COALESCE(source_type, ''), COALESCE(source_id, ''), installment_number);

CREATE TABLE financial_settlements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  financial_entry_id BIGINT NOT NULL REFERENCES financial_entries(id),
  financial_account_id BIGINT NOT NULL REFERENCES financial_accounts(id),
  amount DECIMAL(15,2) NOT NULL,
  interest_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  discount_amount DECIMAL(15,2) NOT NULL DEFAULT 0,
  settled_at TIMESTAMP NOT NULL,
  user_id BIGINT NOT NULL REFERENCES users(id),
  notes VARCHAR(255),
  idempotency_key VARCHAR(100),
  reversed_settlement_id BIGINT,
  CHECK (amount > 0)
);
CREATE UNIQUE INDEX ux_settlement_idempotency ON financial_settlements (financial_entry_id, idempotency_key);

CREATE TABLE print_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  product_id BIGINT REFERENCES products(id),
  quantity INTEGER NOT NULL,
  method VARCHAR(30) NOT NULL,
  settings_json TEXT,
  printed_at TIMESTAMP NOT NULL
);

CREATE TABLE import_jobs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  user_id BIGINT NOT NULL REFERENCES users(id),
  import_type VARCHAR(40) NOT NULL,
  original_name VARCHAR(255) NOT NULL,
  status VARCHAR(20) NOT NULL,
  total_rows INTEGER NOT NULL DEFAULT 0,
  valid_rows INTEGER NOT NULL DEFAULT 0,
  invalid_rows INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL,
  confirmed_at TIMESTAMP
);

CREATE TABLE import_job_rows (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  import_job_id BIGINT NOT NULL REFERENCES import_jobs(id) ON DELETE CASCADE,
  row_number INTEGER NOT NULL,
  data_json TEXT NOT NULL,
  errors_json TEXT,
  status VARCHAR(20) NOT NULL,
  UNIQUE (import_job_id, row_number)
);

CREATE TABLE user_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  session_hash VARCHAR(128) NOT NULL UNIQUE,
  ip_address VARCHAR(64),
  user_agent VARCHAR(500),
  last_activity_at TIMESTAMP NOT NULL,
  logged_out_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL
);

CREATE TABLE suspended_sales (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  company_id BIGINT NOT NULL REFERENCES companies(id),
  branch_id BIGINT NOT NULL REFERENCES branches(id),
  operator_id BIGINT NOT NULL REFERENCES users(id),
  customer_id BIGINT REFERENCES customers(id),
  idempotency_key VARCHAR(100) NOT NULL,
  label VARCHAR(100),
  payload_json TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'open',
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL,
  completed_sale_id BIGINT REFERENCES sales(id),
  UNIQUE (company_id, idempotency_key)
);

CREATE TABLE php_sessions (
  id VARCHAR(128) PRIMARY KEY,
  data TEXT NOT NULL,
  last_activity INTEGER NOT NULL
);

CREATE INDEX idx_login_attempts_lookup ON login_attempts (email, ip_address, attempted_at);
CREATE INDEX idx_audit_logs_entity ON audit_logs (company_id, entity_type, entity_id, created_at);
CREATE INDEX idx_products_search ON products (company_id, active, description);
CREATE INDEX idx_stock_product ON stock_movements (company_id, location_id, product_id, occurred_at);
CREATE INDEX idx_cash_sessions_open ON cash_sessions (company_id, cash_register_id, status);
